  function current() { return localStorage.getItem('cubelight-lang') || 'en'; }

  function apply(lang) {
    if (LANGS.indexOf(lang) === -1) lang = 'en';
    localStorage.setItem('cubelight-lang', lang);
    var dir = DIRS[lang] === 'rtl' ? 'rtl' : 'ltr';
    document.documentElement.setAttribute('lang', lang);
    document.documentElement.setAttribute('dir', dir);
    var d = DICTS[lang];
    document.querySelectorAll('[data-i18n]').forEach(function (el) {
      var v = d[el.getAttribute('data-i18n')];
      if (v !== undefined) { if (el.hasAttribute('data-i18n-html')) el.innerHTML = v; else el.textContent = v; }
    });
    document.querySelectorAll('select.lang-select').forEach(function (s) { s.value = lang; });
  }

  function mount(currentLang) {
    var sel = document.querySelector('select.lang-select');
    if (sel) {
      LANGS.forEach(function (code) {
        var o = document.createElement('option');
        o.value = code; o.textContent = NAMES[code];
        sel.appendChild(o);
      });
      sel.addEventListener('change', function () { apply(sel.value); });
    }
    apply(currentLang || current());
  }

  return { LANGS: LANGS, NAMES: NAMES, mount: mount, apply: apply, current: current };
